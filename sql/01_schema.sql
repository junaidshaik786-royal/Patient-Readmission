-- MySQL 8 source schema for the publicly released UCI diabetic_data.csv.
-- Portfolio reproducibility companion, not the original course-submitted DDL.
CREATE DATABASE IF NOT EXISTS healthcare;
USE healthcare;
CREATE TABLE IF NOT EXISTS diabetic_data (
  encounter_id BIGINT,
  patient_nbr BIGINT,
  race VARCHAR(200),
  gender VARCHAR(200),
  age VARCHAR(200),
  weight VARCHAR(200),
  admission_type_id INT,
  discharge_disposition_id INT,
  admission_source_id INT,
  time_in_hospital INT,
  payer_code VARCHAR(200),
  medical_specialty VARCHAR(200),
  num_lab_procedures INT,
  num_procedures INT,
  num_medications INT,
  number_outpatient INT,
  number_emergency INT,
  number_inpatient INT,
  diag_1 VARCHAR(200),
  diag_2 VARCHAR(200),
  diag_3 VARCHAR(200),
  number_diagnoses INT,
  max_glu_serum VARCHAR(200),
  A1Cresult VARCHAR(200),
  metformin VARCHAR(200),
  repaglinide VARCHAR(200),
  nateglinide VARCHAR(200),
  chlorpropamide VARCHAR(200),
  glimepiride VARCHAR(200),
  acetohexamide VARCHAR(200),
  glipizide VARCHAR(200),
  glyburide VARCHAR(200),
  tolbutamide VARCHAR(200),
  pioglitazone VARCHAR(200),
  rosiglitazone VARCHAR(200),
  acarbose VARCHAR(200),
  miglitol VARCHAR(200),
  troglitazone VARCHAR(200),
  tolazamide VARCHAR(200),
  examide VARCHAR(200),
  citoglipton VARCHAR(200),
  insulin VARCHAR(200),
  `glyburide-metformin` VARCHAR(200),
  `glipizide-metformin` VARCHAR(200),
  `glimepiride-pioglitazone` VARCHAR(200),
  `metformin-rosiglitazone` VARCHAR(200),
  `metformin-pioglitazone` VARCHAR(200),
  `change` VARCHAR(200),
  diabetesMed VARCHAR(200),
  readmitted VARCHAR(200)
);
